-- Permanent widget install (Phase 1). A workspace gets a publishable key (pk_live_/pk_test_ + 24 chars) that
-- can sit on any page forever. The key never opens anything by itself: on the visitor's first open the server
-- (service role, after its own origin and rate checks) creates an ordinary support_cases row with a fresh
-- 24-hour token, so /help, answers, handoff, owner replies and billing lookups run exactly as for a demo case.
-- Keys are public by design (they ship in page HTML); the origin rules, rate limits, per-conversation and
-- daily caps are what bound their use.

-- 1. Cases now come from two sources: the owner's one-hour demo (fictional fixture order) or a real widget
--    visitor (no fixture order at all).
ALTER TABLE public.support_cases ADD COLUMN source text NOT NULL DEFAULT 'demo' CHECK(source IN('demo','widget'));
ALTER TABLE public.support_cases DROP CONSTRAINT support_cases_fictional_check;
ALTER TABLE public.support_cases DROP CONSTRAINT support_cases_amount_check;
ALTER TABLE public.support_cases ALTER COLUMN order_label DROP NOT NULL;
ALTER TABLE public.support_cases ALTER COLUMN amount DROP NOT NULL;
ALTER TABLE public.support_cases ADD CONSTRAINT support_cases_source_shape CHECK(
 (source='demo' AND fictional AND order_label IS NOT NULL AND amount>0 AND amount<=1000)
 OR (source='widget' AND NOT fictional AND order_label IS NULL AND amount IS NULL));
CREATE INDEX support_cases_widget_day ON public.support_cases(user_id,created_at) WHERE source='widget';
-- Signed-in clients may still create only demo cases (app/api/support create_demo).
DROP POLICY ws_create_support_cases ON public.support_cases;
CREATE POLICY ws_create_support_cases ON public.support_cases FOR INSERT TO authenticated
 WITH CHECK(user_id=(select public.acting_workspace()) AND (select public.workspace_role_at_least('manager')) AND source='demo');

-- 2. The visitor view reports what kind of case it is. Widget cases carry no order, so the fictional order
--    card (lib/billing-preview.ts) is hidden for them automatically.
CREATE OR REPLACE FUNCTION public.support_case_view_base(p_hash text) RETURNS jsonb
LANGUAGE sql SECURITY DEFINER SET search_path=public AS $$
 SELECT jsonb_build_object('id',c.id,'order',c.order_label,'amount',c.amount,'currency',c.currency,'fictional',c.fictional,'source',c.source,
  'status',CASE WHEN c.source='demo' THEN 'Sandbox fixture - no real order or payment' ELSE 'Website chat' END,'expiresAt',c.expires_at,
  'branding',jsonb_build_object('label',coalesce(s.label,'Site help'),'color',coalesce(s.color,'#233de8'),'initials',coalesce(s.initials,'AP'),'prompts',coalesce(s.prompts,'["Ask a question","Talk to a person"]'::jsonb)))
 FROM public.support_cases c LEFT JOIN public.widget_settings s ON s.user_id=c.user_id WHERE c.token_hash=p_hash AND c.expires_at>now();
$$;
REVOKE ALL ON FUNCTION public.support_case_view_base(text) FROM PUBLIC,anon,authenticated;

-- 3. The key itself, on the workspace's widget settings.
ALTER TABLE public.widget_settings ADD COLUMN public_key text UNIQUE CHECK(public_key ~ '^pk_(live|test)_[A-Za-z0-9]{24}$');
ALTER TABLE public.widget_settings ADD COLUMN key_active boolean NOT NULL DEFAULT true;
ALTER TABLE public.widget_settings ADD COLUMN key_rotated_at timestamptz;
-- Managers can write widget_settings directly (043 policy). The key columns change only through the RPCs
-- below, which set a transaction-local flag; any other write that touches them is refused.
CREATE FUNCTION public.guard_widget_key() RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 IF coalesce(current_setting('app.widget_key_rpc',true),'')<>'1' AND (
   (TG_OP='INSERT' AND (NEW.public_key IS NOT NULL OR NEW.key_active IS DISTINCT FROM true OR NEW.key_rotated_at IS NOT NULL))
   OR (TG_OP='UPDATE' AND ROW(NEW.public_key,NEW.key_active,NEW.key_rotated_at) IS DISTINCT FROM ROW(OLD.public_key,OLD.key_active,OLD.key_rotated_at))) THEN
  RAISE EXCEPTION 'Widget key changes go through rotate_widget_key or set_widget_key_active';
 END IF;
 RETURN NEW;
END$$;
CREATE TRIGGER guard_widget_key BEFORE INSERT OR UPDATE ON public.widget_settings FOR EACH ROW EXECUTE FUNCTION public.guard_widget_key();

-- Owner/admin/manager: set a new key (generated by the server, 144 bits) and turn it on. The old key stops
-- working at once; visitor conversations already open keep their own 24-hour tokens.
CREATE FUNCTION public.rotate_widget_key(p_key text) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE ws uuid:=public.acting_workspace();
BEGIN
 IF ws IS NULL OR NOT public.workspace_role_at_least('manager') THEN RAISE EXCEPTION 'Manager role required';END IF;
 IF p_key IS NULL OR p_key !~ '^pk_(live|test)_[A-Za-z0-9]{24}$' THEN RAISE EXCEPTION 'Invalid key';END IF;
 PERFORM set_config('app.widget_key_rpc','1',true);
 INSERT INTO widget_settings(user_id,public_key,key_active,key_rotated_at) VALUES(ws,p_key,true,now())
  ON CONFLICT(user_id) DO UPDATE SET public_key=excluded.public_key,key_active=true,key_rotated_at=now();
 PERFORM set_config('app.widget_key_rpc','',true);
 RETURN true;
END$$;
CREATE FUNCTION public.set_widget_key_active(p_active boolean) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE ws uuid:=public.acting_workspace();n integer;
BEGIN
 IF ws IS NULL OR NOT public.workspace_role_at_least('manager') THEN RAISE EXCEPTION 'Manager role required';END IF;
 IF p_active IS NULL THEN RAISE EXCEPTION 'Invalid value';END IF;
 PERFORM set_config('app.widget_key_rpc','1',true);
 UPDATE widget_settings SET key_active=p_active WHERE user_id=ws AND public_key IS NOT NULL;
 GET DIAGNOSTICS n=ROW_COUNT;
 PERFORM set_config('app.widget_key_rpc','',true);
 IF n=0 THEN RETURN false;END IF;
 RETURN true;
END$$;
REVOKE ALL ON FUNCTION public.rotate_widget_key(text),public.set_widget_key_active(boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.rotate_widget_key(text),public.set_widget_key_active(boolean) TO authenticated;

-- 4. Service-role only (app/api/widget and app/api/widget/session, after origin and rate checks).
-- Settings for an active key, in the same shape support_case_view gives the widget.
CREATE FUNCTION public.widget_key_view(p_key text) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT jsonb_build_object('label',s.label,'color',s.color,'initials',s.initials,'prompts',s.prompts,'controls',s.controls,'mode',CASE WHEN s.public_key LIKE 'pk_test_%' THEN 'test' ELSE 'live' END)
 FROM widget_settings s WHERE s.public_key=p_key AND s.key_active AND p_key ~ '^pk_(live|test)_[A-Za-z0-9]{24}$';
$$;
-- Opens one visitor conversation for an active key. 5000 new conversations per workspace per UTC day.
CREATE FUNCTION public.widget_open_session(p_key text,p_token_hash text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE s widget_settings;cid uuid:=gen_random_uuid();exp timestamptz:=now()+interval '24 hours';
BEGIN
 IF p_token_hash IS NULL OR p_token_hash !~ '^[a-f0-9]{64}$' THEN RAISE EXCEPTION 'Invalid token';END IF;
 SELECT * INTO s FROM widget_settings WHERE public_key=p_key AND key_active;
 IF NOT FOUND THEN RETURN NULL;END IF;
 IF(SELECT count(*) FROM support_cases WHERE user_id=s.user_id AND source='widget' AND created_at>=date_trunc('day',now()))>=5000 THEN RAISE EXCEPTION 'Daily conversation limit reached';END IF;
 INSERT INTO support_cases(id,user_id,token_hash,expires_at,order_label,amount,fictional,source)
  VALUES(cid,s.user_id,p_token_hash,exp,NULL,NULL,false,'widget');
 RETURN jsonb_build_object('id',cid,'expiresAt',exp);
END$$;
REVOKE ALL ON FUNCTION public.widget_key_view(text),public.widget_open_session(text,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.widget_key_view(text),public.widget_open_session(text,text) TO service_role;

-- 5. Owner-set questions per conversation (controls.maxQuestions, 1-50, default 20; SiteGPT calls this rate
--    limiting). Same function as 032 otherwise; the 100 answers per workspace per UTC day budget is unchanged
--    until plan limits (Phase 2) replace it.
CREATE OR REPLACE FUNCTION public.support_reserve_knowledge(p_hash text,p_question text) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE c public.support_cases;rid uuid;cap integer:=20;ctl jsonb;
BEGIN
 IF p_question IS NULL OR length(trim(p_question)) NOT BETWEEN 3 AND 500 THEN RAISE EXCEPTION 'Invalid question';END IF;
 SELECT * INTO c FROM support_cases WHERE token_hash=p_hash AND expires_at>now() FOR UPDATE;
 IF NOT FOUND OR c.inbox_state IN('taken_over','closed') THEN RAISE EXCEPTION 'AI paused: case taken over, closed or expired';END IF;
 SELECT controls INTO ctl FROM widget_settings WHERE user_id=c.user_id;
 IF jsonb_typeof(ctl->'maxQuestions')='number' THEN cap:=least(greatest(floor((ctl->>'maxQuestions')::numeric)::integer,1),50);END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(c.user_id::text,0));
 IF(SELECT count(*) FROM knowledge_interactions WHERE case_id=c.id)>=cap THEN RAISE EXCEPTION 'Conversation question limit reached';END IF;
 IF(SELECT count(*) FROM knowledge_interactions WHERE user_id=c.user_id AND created_at>=date_trunc('day',now()))>=100 THEN RAISE EXCEPTION 'Demo question budget reached';END IF;
 INSERT INTO knowledge_interactions(user_id,case_id,question,supported,source_count) VALUES(c.user_id,c.id,p_question,false,0) RETURNING id INTO rid;RETURN rid;
END;
$$;
