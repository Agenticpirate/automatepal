/* Visitor-facing text of the chat panel (/help) and the widget button, in the languages the Widget studio
   offers. The owner picks a language or "auto" (the visitor's browser language, falling back to English).
   AI answers follow the visitor's own language separately; this only covers the fixed interface text.
   Demo-mode wording (APP_MODE=preview, lib/app-mode.ts) stays English. */
export type WidgetLang = 'en' | 'es' | 'fr' | 'de' | 'pt' | 'hi' | 'te';
export const LANG_NAMES: Record<WidgetLang, string> = {en: 'English', es: 'Español', fr: 'Français', de: 'Deutsch', pt: 'Português', hi: 'हिन्दी', te: 'తెలుగు'};
const SUPPORTED = Object.keys(LANG_NAMES) as WidgetLang[];

export function resolveLang(setting: string | null | undefined, browser: readonly string[] = []): WidgetLang {
  if (setting && setting !== 'auto' && (SUPPORTED as string[]).includes(setting)) return setting as WidgetLang;
  for (const l of browser) { const base = l.toLowerCase().split('-')[0]; if ((SUPPORTED as string[]).includes(base)) return base as WidgetLang; }
  return 'en';
}

